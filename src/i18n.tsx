const dicts: Record<string, Dict> = { tr, en };

type I18nCtx = { lang: string; setLang: (l: string) => void; t: (k: string) => string };
const Ctx = createContext<I18nCtx>({ lang: "tr", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<string>(() => {
    if (typeof window === "undefined") return "tr";
    return localStorage.getItem("chatly.lang") || "tr";
  });
  useEffect(() => {
    if (typeof window !== "undefined") localStorage.setItem("chatly.lang", lang);
  }, [lang]);
  const t = (k: string) => dicts[lang]?.[k] ?? dicts.tr[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang: setLangState, t }}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
